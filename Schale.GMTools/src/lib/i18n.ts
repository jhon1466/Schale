import { createSignal } from 'solid-js';

export type Lang = 'es' | 'en' | 'zh' | 'ja';

const stored = (typeof localStorage !== 'undefined' ? localStorage.getItem('schale-lang') : null) as Lang | null;
const initial: Lang = stored && ['es', 'en', 'zh', 'ja'].includes(stored) ? stored : 'es';

const [lang, setLangSignal] = createSignal<Lang>(initial);

export function currentLang() {
  return lang();
}

export function setLang(next: Lang) {
  setLangSignal(next);
  if (typeof localStorage !== 'undefined') localStorage.setItem('schale-lang', next);
  if (typeof document !== 'undefined') document.documentElement.lang = next;
}

